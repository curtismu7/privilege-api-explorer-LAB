#!/usr/bin/env node
/**
 * Generates docs/talk-track.md (a static script for this app — no story files, no verticals), so the file and this
 * builder cannot drift: a test compares the committed file with this builder's output.
 *   node scripts/build-talk-track.mjs      (npm run talk-track)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TALK_PATH = path.join(ROOT, 'docs', 'talk-track.md');

export function buildTalkTrack() {
  return `# Privilege API Explorer LAB: talk track

Generated by \`npm run talk-track\`. Do not edit by hand.

Before you start, say which mode you are in: the header toggle, the \`Mode:\` chip and the banner all show it. **Mock** is simulated (an in-process mock of the Privilege console API on this machine; the sample tenant is illustrative, not a recording). **Real** is owner-run, refused until the owner opts in, and acts on the real console with the saved API key and secret.

Press P (or the Present button) for presenter mode: larger text, and the banner and the mode stay on screen. Esc leaves it. Reset (header) puts the demo back to its start: audit history cleared, writes off, the mock's sample tenant restored, and the diagram boxes.

## 1. Sign in to a console

**Do:** open Connections (Mock is already set up by the owner, or press **Add mock console connection**). Press **Test connection**.

**Say:** "One connection is one console origin, one tenant id and one API key/secret pair. The secret is write-only — after saving it shows as 'set', and it is never returned by the API or written to a log. The test is one real GET against the console, so a green check means the credential was accepted."

**Why it matters:** the login story is the product story: an API key is a machine identity, and this app treats it like one — write-only, audited, revocable by deleting the connection.

## 2. Find the API you want

**Do:** open Explorer. Type \`pi\` in the search box.

**Say:** "447 operations from the console's own swagger. The search is a plain substring match across method, path, service and summary — type 'pi' and you see every pi* path. Narrow by service or by method. No magic, no guessing: the catalog is the console's own spec."

**Why it matters:** the full surface is visible, including the operations a scoped key will refuse. What the console refuses, the explorer shows.

## 3. Run one call, live

**Do:** open a GET operation (users), press **Call**.

**Say:** "Parameters come from the spec's own path template — the tenant is filled from the connection. The result pane is real time: HTTP status, elapsed milliseconds, the exact path that was called, a fresh session id, and the raw body. This is Mock, so the answer is the in-process sample tenant. In Real, this same pane carries the console's own answer — including its refusals."

**Why it matters:** one pane, one call, no hidden layers: what you see is what the console sent.

## 4. Writes are gated

**Do:** open a DELETE operation with writes off. Point at the hint. (Optional, owner call: enable writes on the connection and run it against the mock.)

**Say:** "Read-only by default. POST and PUT need the per-connection switch; DELETE and PATCH always need it. A blocked call is a 403 and an audit line. The console's own 401 or 403 — wrong key, scope too small — is passed through and shown as-is."

**Why it matters:** the demo can explore an admin plane without being able to change it by accident.

## 5. The evidence

**Do:** open Audit. Then Diagram, press Simulate.

**Say:** "Every call — ok, refused, blocked or error — is in the audit, redacted. The diagram shows the path: browser, this app, console. In Mock nothing leaves this machine; in Real the app reaches only the console origin of the connection you use."

**Why it matters:** the demo proves its own claims. The audit is the receipt.

## Caveats to say out loud

- Mock is a mock: the sample tenant is illustrative, not a recording, and write calls change only the in-memory sample.
- Real was verified once against a **local desktop console** with a scoped key. It has **not** been verified against a cloud tenant: which collections a given key may read is the console's own answer, shown as-is.
- The \`appusertoken\` JWT flow from the console docs (encrypted credentials via a Go helper) is **not implemented** — the encryption scheme is undocumented. The key/secret header scheme is the implemented login.
- Product claims about the console's behavior are the console's own answers here, not Ping documentation claims; anything this app itself asserts beyond that is marked UNVERIFIED.
`;
}
export const serialize = (s) => s;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(TALK_PATH, buildTalkTrack());
  console.log(`wrote ${TALK_PATH}`);
}
