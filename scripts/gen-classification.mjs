// Generates docs/classification.md from the golden table (server/test/golden.js) and the live classifier.
// `node scripts/gen-classification.mjs` writes the file; `--check` exits 1 when the file is stale.
import fs from 'node:fs';
import { classify } from '../server/src/classify.js';
import { GOLDEN } from '../server/test/golden.js';

const out = new URL('../docs/classification.md', import.meta.url);
export function render() {
  const rows = GOLDEN.map(([name, ann, want]) => {
    const c = classify({ name, annotations: ann });
    if (c.class !== want) throw new Error(`golden mismatch for ${name}: ${c.class} != ${want}`);
    return `| \`${name}\` | ${ann ? `\`${JSON.stringify(ann)}\`` : 'none'} | **${c.class}** | ${c.source} |`;
  });
  return `# Tool classification

Generated by \`node scripts/gen-classification.mjs\` from the golden table in \`server/test/golden.js\`; a test fails when this file is stale. Do not edit by hand.

Every tool is read, write or destructive. Order of evidence: the server's annotations (\`destructiveHint\`, \`readOnlyHint\`), then the name's verb. **Unknown is write.**

- read verbs: list, get, read, search, describe, find, query, show, fetch, count, check, validate, lookup, export
- write verbs: create, update, patch, put, set, add, assign, enable, disable, reset, unlock, revoke, import, send, invite, activate, deactivate, rotate, start, stop, run, execute, deploy, link, unlink, move, replace, upsert, register, regenerate, resend, verify
- destructive verbs: delete, remove, purge, wipe, destroy, erase, drop

A name that mixes classes takes the worst one (\`getOrCreateUser\` is write, \`listThenDeleteUsers\` is destructive). A \`readOnlyHint:true\` annotation is **not** honoured when the name starts with, or contains, a write or destructive verb, nor when the name has no recognised verb at all (unknown name plus a read hint stays write): a wrong or lying annotation must not open a write path. \`destructiveHint:true\` always wins.

What each class costs: read calls run. Write and destructive calls are blocked until "allow writes" is on for the connection, then need \`{confirm:true, argsHash}\` for the exact arguments; destructive calls also need the tool name typed.

| Tool name | Annotations | Class | Decided by |
| --- | --- | --- | --- |
${rows.join('\n')}
`;
}
if (process.argv[1] === new URL(import.meta.url).pathname) {
  const text = render();
  if (process.argv.includes('--check')) { const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''; if (cur !== text) { console.error('docs/classification.md is stale: run node scripts/gen-classification.mjs'); process.exit(1); } }
  else fs.writeFileSync(out, text);
}
